export const BUILTIN_CONCEPT_LIST_VERSION = "swadesh-classic-v1";

export function builtInConcepts(kind: "swadesh-100" | "swadesh-207"): Concept[] {
  const values = kind === "swadesh-100" ? SWADESH_100 : SWADESH_207;
  return values.map((gloss, position) => ({
    id: `${kind}-${position + 1}`,
    conceptKey: `${kind}:${position + 1}`,
    gloss,
    position,
  }));
}

export function builtInConceptCount(kind: "swadesh-100" | "swadesh-207"): number {
  return (kind === "swadesh-100" ? SWADESH_100 : SWADESH_207).length;
}
